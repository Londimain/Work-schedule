            "Шапка таблицы (№, ФИО, Должность, В таблицу, Действия) "
            "зафиксирована сверху и не прокручивается вместе со "
            "списком.\n\n"
            "Галочка «В таблицу» определяет, будет ли сотрудник "
            "отображаться в табеле. Одновременно табель может "
            "вестись только по одному отделу — при попытке "
            "включить сотрудника другого отдела программа "
            "предупредит и не даст этого сделать.\n\n"
            "У нового сотрудника галочка «В таблицу» по умолчанию "
            "снята — её нужно поставить вручную, когда решите "
            "включить человека в табель.\n\n"
